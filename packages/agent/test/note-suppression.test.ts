import test from 'node:test';
import assert from 'node:assert/strict';
import {mkdtemp,rm} from 'node:fs/promises';
import {tmpdir} from 'node:os';
import {join} from 'node:path';
import {MemoryBrain,SQLiteBrain} from '../../brain/src/index.js';
import {ThoughtConsolidator} from '../src/thoughts.js';
import {Agent} from '../src/index.js';
import {FixtureProviders} from '../../agent-host/src/providers.js';
import type {BrainPort,Segment,ThoughtInput,ThoughtResult,RouteDecision} from '../../contracts/src/index.js';
import {formatMarkdown,parseMarkdown} from '../../contracts/src/markdown.js';
const now=()=> '2026-10-10T12:00:00Z';
const segment=(id:string,text:string,revision=1,final=true):Segment=>({id,turnId:id,text,revision,final,speaker:'user',createdAt:now()});
const result=(i:ThoughtInput):ThoughtResult=>({groups:[{title:'Study thought',summary:i.segments.map(s=>s.text).join(' '),spans:i.segments.map(s=>({segmentId:s.id,revision:s.revision,start:0,end:s.text.length})),continuesActive:!!i.activeNote,ongoing:true}],remainder:[]});
for(const adapter of ['memory','sqlite']) {
  async function setup() {
    const dir=await mkdtemp(join(tmpdir(),'moo-retention-'));
    let brain:BrainPort=adapter==='memory'?new MemoryBrain():new SQLiteBrain(dir);
    await brain.createRecord({id:'session',kind:'session',createdAt:now()});
    let infer=async(i:ThoughtInput)=>result(i),calls=0;
    const make=()=>new ThoughtConsolidator({brain,now,emit:()=>{},notice:()=>{},context:async()=>'',enrich:async()=>{},generation:{summarize:async()=>({title:'',summary:''}),respond:async()=>({text:'',toolCalls:[]}),consolidate:async i=>{calls++;return infer(i);}}});
    let engine=make();
    return {get brain(){return brain},get engine(){return engine},get calls(){return calls},set infer(value:typeof infer){infer=value},
      async add(s:Segment){await brain.upsertSegment('session',s);await engine.append('session',[s]);},
      async restart(){if(adapter==='sqlite'){await brain.close();brain=new SQLiteBrain(dir)}engine=make();await engine.recover('session');},
      async close(){await brain.close();await rm(dir,{recursive:true,force:true});}};
  }
  test(`${adapter}: suppression is durable, hidden everywhere, and new speech creates a fresh note`,async()=>{
    const t=await setup();try {
      await t.add(segment('a','Private thought to omit as a note.'));
      const draft=(await t.brain.query({kinds:['dictation']}))[0]!;
      assert.equal((await t.engine.suppress('session')).status,'suppressed');
      const retained=(await t.brain.getRecord(draft.id))!;
      assert.ok(retained.suppressed);assert.equal((await t.brain.search('Private',5,{kinds:['dictation']})).length,0);
      assert.equal((await t.brain.query({})).length,1,'Only the original session remains in an unfiltered query');
      assert.deepEqual(await t.brain.related(draft.id),[]);
      assert.ok(parseMarkdown(formatMarkdown(retained)).record?.suppressed);
      await t.restart();await t.add(segment('a','Corrected private thought.',2));await t.engine.process('session');
      assert.equal(t.calls,0,'Suppressed original cannot be regenerated by correction or restart');
      assert.equal((await t.brain.getRecord('session'))!.segments[0]!.text,'Corrected private thought.');
      await t.add(segment('b','New independent thought.'));await t.engine.process('session');
      const notes=(await t.brain.query({kinds:['dictation']}));assert.equal(notes.length,1);assert.notEqual(notes[0]!.id,draft.id);
      assert.equal(notes[0]!.summary,'New independent thought.');
    }finally{await t.close();}
  });
  test(`${adapter}: active source preview grows without modifying accepted summary or invoking a model`,async()=>{
    const t=await setup();try {
      await t.add(segment('a','First point.'));await t.engine.process('session');
      const note=(await t.brain.query({kinds:['dictation']}))[0]!;
      await t.add(segment('b','Second point.'));
      await t.add(segment('c','The third point',1,false));
      const preview=await t.engine.preview('session');assert.equal(preview!.recordId,note.id);
      assert.deepEqual(preview!.segments.map(s=>s.text),['Second point.','The third point']);
      assert.equal(preview!.segments[1]!.final,false);assert.equal(t.calls,1);
      assert.equal((await t.brain.getRecord(note.id))!.summary,'First point.');
      await t.add(segment('c','The third corrected point',2,false));
      assert.notEqual((await t.engine.preview('session'))!.revision,preview!.revision);
    }finally{await t.close();}
  });
  test(`${adapter}: pending new topic asks confirmation; stale confirmation never suppresses a newer scope`,async()=>{
    const t=await setup();try {
      await t.add(segment('a','Original topic.'));await t.engine.process('session');
      await t.add(segment('b','Possibly another topic.'));
      const proposed=await t.engine.suppress('session');assert.equal(proposed.status,'clarify');
      await t.add(segment('c','More pending content.'));
      const stale=await t.engine.suppress('session',proposed.status==='clarify'?proposed.proposalId:undefined);
      assert.equal(stale.status,'clarify');assert.equal((await t.brain.query({kinds:['dictation']})).length,1);
      const done=await t.engine.suppress('session',stale.status==='clarify'?stale.proposalId:undefined);
      assert.equal(done.status,'suppressed');assert.equal((await t.brain.query({kinds:['dictation']})).length,0);
    }finally{await t.close();}
  });
  test(`${adapter}: late provider result cannot resurrect suppressed source or fail new work`,async()=>{
    const t=await setup();try {
      let release!:(value:ThoughtResult)=>void,input!:ThoughtInput;
      t.infer=i=>{input=i;return new Promise(r=>release=r)};
      await t.add(segment('a','Source being organized.'));
      const work=t.engine.process('session');while(!release)await new Promise(r=>setTimeout(r,1));
      await t.engine.suppress('session');await t.add(segment('b','Fresh source.'));
      release(result(input));await work;
      assert.equal((await t.brain.query({kinds:['dictation']})).length,1);
      const state=await t.brain.getState<any>('thought-buffer:session');assert.notEqual(state.status,'failed');assert.equal(state.spans[0].segmentId,'b');
      t.infer=async i=>result(i);await t.engine.process('session');assert.equal((await t.brain.query({kinds:['dictation']}))[0]!.summary,'Fresh source.');
    }finally{await t.close();}
  });
  test(`${adapter}: suppression intent resumes after a crash before record update`,async()=>{
    const t=await setup();try {
      await t.add(segment('a','Retained source.'));
      const update=t.brain.updateRecord.bind(t.brain);let fail=true;
      t.brain.updateRecord=async(...args)=>{if(args[2].suppressed&&fail){fail=false;throw Error('crash')}return update(...args)};
      await assert.rejects(t.engine.suppress('session'),/crash/);t.brain.updateRecord=update;
      await t.restart();await t.restart();assert.equal((await t.brain.query({kinds:['dictation']})).length,0);assert.equal(t.calls,0);
      assert.equal((await t.brain.getRecord('session'))!.segments.length,1);
    }finally{await t.close();}
  });
}

test('Agent routes retention at 0.8, retains controls, and keeps the conversation open',async()=>{
  const brain=new MemoryBrain(),p=new FixtureProviders();let id=0,route:RouteDecision={route:'start_agent',confidence:1};const spoken:string[]=[];
  const a=new Agent({brain,decisions:{route:async()=>route,tag:p.tag.bind(p),connect:p.connect.bind(p)},generation:p,search:p,vision:p,capture:{capture:async()=>{throw Error('No capture')}},speech:{speak:async s=>{spoken.push(s)},stop:async()=>{}},now,id:()=>String(++id)});
  await a.initialize();await a.submitText('Moo, discuss this thought.');await a.drain();
  const before=a.getState().conversationId;
  route={route:'suppress_note',confidence:.79};await a.submitText("Don't save that.");await a.drain();
  assert.equal(a.getState().pendingOffer?.kind,'note_suppression');assert.ok((await brain.query({kinds:['dictation']})).length);
  route={route:'suppress_note',confidence:.9};await a.submitText('Yes.');await a.drain();
  assert.equal(a.getState().conversationId,before);assert.equal((await brain.query({kinds:['dictation']})).length,0);
  assert.ok(spoken.includes('I won’t keep a note of that. The transcript is retained.'));
  assert.ok((await brain.getRecord(a.getState().sessionId!))!.segments.some(s=>s.text==="Don't save that."));
  await brain.close();
});
